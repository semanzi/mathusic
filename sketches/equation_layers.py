"""
equation_layers.py

A generic structure for generating music from mathematical equations with SCAMP.

Each Layer reads its pitch, duration and volume from equations of the form
f(t, n), where t is the layer's elapsed time in beats and n is its step count.
An equation may be supplied as a Python callable, a string expression such as
"sin(t) * 12 + 60", or a plain number (treated as a constant). A pitch equation
that returns None or NaN produces a rest.

Equations and instruments can be swapped at any time, including mid-performance,
because each layer re-reads them on every step.

Requires:  pip install scamp
"""

from __future__ import annotations

import math
from typing import Callable, Optional, Sequence, Union

from scamp import Session, current_clock, wait

Equation = Callable[[float, int], Optional[float]]
EquationLike = Union[Equation, str, float, int, None]


# ---------------------------------------------------------------------------
# Equation handling
# ---------------------------------------------------------------------------

_SAFE_NAMES = {k: getattr(math, k) for k in dir(math) if not k.startswith("_")}
_SAFE_NAMES.update(abs=abs, min=min, max=max, round=round, int=int, float=float)
_VARIABLES = ("t", "n")


def expression(text: str) -> Equation:
    """Turn a string such as 'sin(t * 0.5) * 12 + 72' into an equation f(t, n).

    Only names from the math module, a few builtins and the variables t and n
    are permitted. This is a convenience guard rather than a security sandbox,
    so it should not be given untrusted input.
    """
    code = compile(text, "<equation>", "eval")
    for name in code.co_names:
        if name not in _SAFE_NAMES and name not in _VARIABLES:
            raise ValueError(f"Name not permitted in equation: {name!r}")

    def equation(t: float, n: int) -> float:
        return eval(code, {"__builtins__": {}}, {**_SAFE_NAMES, "t": t, "n": n})

    equation.source = text
    return equation


def as_equation(value: EquationLike) -> Optional[Equation]:
    """Normalise a callable, string or number into an equation f(t, n)."""
    if value is None:
        return None
    if isinstance(value, str):
        return expression(value)
    if isinstance(value, (int, float)):
        constant = float(value)
        return lambda t, n: constant
    if callable(value):
        return value
    raise TypeError(f"Cannot interpret {value!r} as an equation")


# ---------------------------------------------------------------------------
# Mapping helpers
# ---------------------------------------------------------------------------

MAJOR = (0, 2, 4, 5, 7, 9, 11)
NATURAL_MINOR = (0, 2, 3, 5, 7, 8, 10)
MAJOR_PENTATONIC = (0, 2, 4, 7, 9)
MINOR_PENTATONIC = (0, 3, 5, 7, 10)
CHROMATIC = tuple(range(12))


def scale_range(in_low: float, in_high: float,
                out_low: float, out_high: float) -> Callable[[float], float]:
    """Linearly map (and clamp) an equation's output range onto a pitch range."""
    span = in_high - in_low

    def mapper(x: float) -> float:
        x = min(max(x, in_low), in_high)
        return out_low + (x - in_low) / span * (out_high - out_low)

    return mapper


def quantise(pitch: float, scale: Sequence[int] = MAJOR, root: int = 60) -> int:
    """Snap a pitch to the nearest degree of a scale built on root."""
    octave, degree = divmod(round(pitch) - root, 12)
    nearest = min(tuple(scale) + (12,), key=lambda s: abs(s - degree))
    return root + octave * 12 + nearest


# ---------------------------------------------------------------------------
# Layer
# ---------------------------------------------------------------------------

class Layer:
    """One voice whose notes are generated by equations."""

    TARGETS = ("pitch", "duration", "volume")

    def __init__(self, name: str, part, pitch: EquationLike,
                 duration: EquationLike = 0.5, volume: EquationLike = 0.7,
                 pitch_map: Optional[Callable[[float], float]] = None,
                 scale: Optional[Sequence[int]] = None, root: int = 60,
                 steps: Optional[int] = None, min_duration: float = 0.0625):
        self.name = name
        self.part = part
        self.pitch = as_equation(pitch)
        self.duration = as_equation(duration)
        self.volume = as_equation(volume)
        self.pitch_map = pitch_map
        self.scale = scale
        self.root = root
        self.steps = steps            # None means run until stopped
        self.min_duration = min_duration
        self.active = False
        self.clock = None

    def set_equation(self, target: str, value: EquationLike) -> None:
        if target not in self.TARGETS:
            raise ValueError(f"target must be one of {self.TARGETS}")
        setattr(self, target, as_equation(value))

    def _next_pitch(self, t: float, n: int) -> Optional[float]:
        try:
            value = self.pitch(t, n)
            if value is None:
                return None
            value = float(value)
        except (ArithmeticError, ValueError):
            return None               # undefined points become rests
        if math.isnan(value):
            return None
        if self.pitch_map:
            value = self.pitch_map(value)
        if self.scale:
            value = quantise(value, self.scale, self.root)
        return min(max(value, 0), 127)

    def _safe(self, equation: Equation, t: float, n: int, fallback: float) -> float:
        try:
            return float(equation(t, n))
        except (ArithmeticError, ValueError, TypeError):
            return fallback

    def run(self) -> None:
        """The loop SCAMP forks onto its own clock."""
        n = 0
        while self.active and (self.steps is None or n < self.steps):
            t = current_clock().beat()
            pitch = self._next_pitch(t, n)
            duration = max(self.min_duration, self._safe(self.duration, t, n, 0.5))
            volume = min(max(self._safe(self.volume, t, n, 0.7), 0.0), 1.0)
            if pitch is None:
                wait(duration)
            else:
                self.part.play_note(pitch, volume, duration)
            n += 1
        self.active = False


# ---------------------------------------------------------------------------
# Composition
# ---------------------------------------------------------------------------

class Composition:
    """Owns the SCAMP session, the instruments and the layers."""

    def __init__(self, tempo: float = 100):
        self.session = Session(tempo=tempo)
        self.layers: dict[str, Layer] = {}
        self._parts: dict[str, object] = {}
        self._playing = False

    # Instruments are General MIDI preset names from the default soundfont,
    # matched by name, e.g. "piano", "cello", "flute", "vibraphone".
    def instrument(self, name: str):
        if name not in self._parts:
            self._parts[name] = self.session.new_part(name)
        return self._parts[name]

    def add_layer(self, name: str, instrument: str, pitch: EquationLike, **options) -> Layer:
        if name in self.layers:
            raise ValueError(f"Layer {name!r} already exists")
        layer = Layer(name, self.instrument(instrument), pitch, **options)
        self.layers[name] = layer
        if self._playing:
            self._launch(layer)
        return layer

    def remove_layer(self, name: str) -> None:
        self.layers.pop(name).active = False

    def set_equation(self, name: str, value: EquationLike, target: str = "pitch") -> None:
        self.layers[name].set_equation(target, value)

    def set_instrument(self, name: str, instrument: str) -> None:
        self.layers[name].part = self.instrument(instrument)

    def set_tempo(self, tempo: float) -> None:
        self.session.tempo = tempo

    def schedule(self, beats_from_now: float, action: Callable, *args, **kwargs) -> None:
        """Run any change (equation, instrument, new layer) after a delay in beats."""
        def task():
            wait(beats_from_now)
            action(*args, **kwargs)
        self.session.fork(task)

    def _launch(self, layer: Layer) -> None:
        layer.active = True
        layer.clock = self.session.fork(layer.run)

    def stop(self) -> None:
        for layer in self.layers.values():
            layer.active = False

    def play(self, beats: Optional[float] = None, record: bool = False):
        """Play every layer.

        With beats=None the call returns only when all layers finish, so at
        least one bound (beats here, or steps on each layer) is needed for
        layers that would otherwise run indefinitely. With record=True the
        SCAMP Performance is returned for notation or saving.
        """
        if record:
            self.session.start_transcribing()
        self._playing = True
        for layer in self.layers.values():
            if not layer.active:
                self._launch(layer)
        if beats is not None:
            self.session.wait(beats)
            self.stop()
        self.session.wait_for_children_to_finish()
        self._playing = False
        return self.session.stop_transcribing() if record else None


