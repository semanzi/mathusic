# Example
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    piece = Composition(tempo=90)

    # String expression, quantised to a major scale, with a volume equation
    piece.add_layer("melody", "piano",
                    pitch="sin(t * 0.5) * 12 + 72",
                    duration=0.5,
                    volume="0.5 + 0.3 * sin(t)",
                    scale=MAJOR)

    # Plain Python callable
    piece.add_layer("bass", "cello",
                    pitch=lambda t, n: 48 + 7 * (n % 3),
                    duration=2, volume=0.6)

    # Raw equation output mapped onto a pitch range, with rhythmic variation
    piece.add_layer("texture", "vibraphone",
                    pitch="(n * 7) % 24",
                    pitch_map=scale_range(0, 23, 60, 84),
                    duration="0.25 if n % 4 else 0.75",
                    volume=0.45,
                    scale=MINOR_PENTATONIC)

    # Live changes during the performance
    piece.schedule(16, piece.set_instrument, "melody", "flute")
    piece.schedule(24, piece.set_equation, "bass", "36 + 12 * abs(cos(t / 4))")
    piece.schedule(32, piece.add_layer, "bells", "tubular bells",
                   pitch="None if n % 3 else 84 + 5 * sin(n)", duration=1, volume=0.5)

    performance = piece.play(beats=48, record=True)
